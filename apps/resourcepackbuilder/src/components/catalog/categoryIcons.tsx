/** The icons of catalog categories: a card without an icon of its own shows its category's. */
import type { ReactNode } from 'react';
import {
  Archive,
  ArrowDownToLine,
  Binary,
  Box,
  Brush,
  ChartSpline,
  Cpu,
  Dices,
  Equal,
  Footprints,
  Gem,
  Globe,
  Hammer,
  Hash,
  Lightbulb,
  MessageSquareText,
  MousePointerClick,
  Package,
  Pickaxe,
  Plug,
  Puzzle,
  RotateCcw,
  Shield,
  Shirt,
  Sofa,
  Sparkles,
  Split,
  Sprout,
  Star,
  Sword,
  User,
  UtensilsCrossed,
  Wand,
  Workflow,
} from 'lucide-react';

const ICONS: Record<string, ReactNode> = {
  common: <Star />,
  shapes: <Box />,
  redstone: <Lightbulb />,
  blockEntities: <Archive />,
  physics: <ArrowDownToLine />,
  placement: <Footprints />,
  plants: <Sprout />,
  food: <UtensilsCrossed />,
  combat: <Sword />,
  tooltip: <MessageSquareText />,
  equipment: <Shirt />,
  armor: <Shield />,
  appearance: <Brush />,
  behavior: <Cpu />,
  interaction: <MousePointerClick />,
  // Logic catalogs (conditions, functions, triggers, number providers, loot, item and furniture behaviors, updaters)
  logic: <Binary />,
  player: <User />,
  item: <Gem />,
  block: <Box />,
  world: <Globe />,
  messages: <MessageSquareText />,
  effects: <Sparkles />,
  furniture: <Sofa />,
  flow: <Workflow />,
  plugins: <Plug />,
  clicks: <MousePointerClick />,
  use: <Wand />,
  breaking: <Pickaxe />,
  fixed: <Equal />,
  ranges: <Hash />,
  distributions: <ChartSpline />,
  drops: <Package />,
  count: <Dices />,
  data: <Split />,
  tools: <Hammer />,
  farming: <Sprout />,
  change: <Wand />,
  reset: <RotateCcw />,
  storage: <Archive />,
  light: <Lightbulb />,
};

/** The icon of a category id, a puzzle piece for unknown ones. */
export function categoryIcon(category: string | undefined): ReactNode {
  return (category && ICONS[category]) ?? <Puzzle />;
}
