/** Platzhalter für „das Modell dieses Items“ (wird beim Export durch den Modell-Pfad ersetzt). */
export const MODEL_TOKEN = '@model';
/** Präfix für hochgeladene Zusatz-Texturen. */
export const ASSET_TOKEN_PREFIX = '@asset:';

export type PropertyGroup = 'general' | 'appearance' | 'attributes' | 'components' | 'mechanics';

export const PROPERTY_GROUPS: Array<{ id: PropertyGroup; label: string; description: string }> = [
  { id: 'general', label: 'Allgemein', description: 'Lore, Unzerstörbarkeit, Item-Flags und mehr' },
  { id: 'appearance', label: 'Aussehen', description: 'Pack-Optionen, Rüstung und Farben' },
  { id: 'attributes', label: 'Attribute & Verzauberungen', description: 'Attribute-Modifier und Verzauberungen' },
  { id: 'components', label: 'Komponenten', description: 'Minecraft-Datenkomponenten (Essen, Werkzeug, Ausrüstung …)' },
  { id: 'mechanics', label: 'Mechaniken', description: 'Nexo-Mechaniken (Möbel, Blöcke, Rucksack, Befehle …)' },
];

export interface PropertyDef {
  id: string;
  group: PropertyGroup;
  /** Pfad im Item-YAML, z.B. ['Components', 'food'] */
  path: string[];
  label: string;
  description: string;
  field: Field;
  defaultValue: () => ConfigValue;
  minVersion?: string;
  /** Letzte Version, in der die Eigenschaft existiert */
  maxVersion?: string;
  /** Diese Eigenschaften schließen sich gegenseitig aus */
  conflicts?: string[];
  /** Hinweis, der über dem Formular angezeigt wird */
  hint?: string;
  docs?: string;
  /** Leeres Objekt trotzdem schreiben (Mechanik aktiv, auch ohne Optionen) */
  keepEmpty?: boolean;
}

