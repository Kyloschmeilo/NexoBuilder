/**
 * Builds the final Nexo YAML object from an item:
 *  1. clean up the structured config (remove empty fields, resolve placeholders)
 *  2. add automatic values (itemname, material, Pack.model, Components.item_model)
 *  3. overlay the user's additional YAML
 */
import { deepClone, deepMerge, isPlainObject, mapData, MODEL_TOKEN } from '@resourcepackbuilder/utils';
import type { ConfigObject, ConfigValue, Item, Project } from '../project/types';
import { slotForMaterial, type ItemArmor } from '../project/armor';
import { getPath, setPath } from '../project/config';
import { effectiveMaterial, itemMaterial } from '../project/item';
import { cleanConfig } from '../form/prune';
import { parseRawYaml, type RawYamlError } from '../yaml';
import { NEXO_FORM } from './form/schema';

/** Order of the keys in the YAML (as in the Nexo docs) */
const TOP_LEVEL_ORDER = [
  'itemname',
  'material',
  'template',
  'templates',
  'lore',
  'color',
  'unbreakable',
  'excludeFromInventory',
  'excludeFromCommands',
  'Pack',
  'Components',
  'AttributeModifiers',
  'Enchantments',
  'ItemFlags',
  'PersistentData',
  'CustomArmor',
  'Mechanics',
];

/** A value the export adds to the configuration (e.g. placements.wall.item_model of an extra model). */
export interface ConfigAddition {
  path: string[];
  value: unknown;
  /** Only set if the user has not entered anything there themselves */
  ifMissing?: boolean;
}

export interface BuildContext {
  project: Project;
  item: Item;
  /** "namespace:path" of the model, or null if the item has no model */
  modelKey: string | null;
  /** The item's usable armor set (null = none) */
  armor?: ItemArmor | null;
  /** Model keys of the variants (e.g. pulling_models → [...]) */
  variantKeys?: Record<string, string | string[] | undefined>;
  /** ItemModel generated by ResourcepackBuilder (inventory icon, connectable furniture) */
  itemModel?: string | null;
  /** Values that additional models need in the config */
  extraConfig?: ConfigAddition[];
}

export interface BuildResult {
  config: Record<string, unknown>;
  rawYamlError: RawYamlError | null;
}

export function buildItemConfig(context: BuildContext): BuildResult {
  const { item, project, modelKey } = context;
  const source = deepClone(item.config);

  // 1. Clean up properties according to the schema
  const cleaned = cleanConfig(NEXO_FORM, source);

  // 2. Resolve placeholders
  const resolved = resolveTokens(cleaned, modelKey) as Record<string, unknown>;

  // 3. Automatic values
  const result: Record<string, unknown> = {};
  const name = item.displayName.trim();
  if (name) result.itemname = name;
  const material = itemMaterial(item);
  result.material = material;
  delete resolved.material;
  delete resolved.itemname;

  if (modelKey) {
    const variants = Object.fromEntries(Object.entries(context.variantKeys ?? {}).filter(([, v]) => v !== undefined && v.length > 0));
    const pack: Record<string, unknown> = { model: modelKey, ...variants, ...section(resolved, 'Pack') };
    resolved.Pack = pack;
    const components = section(resolved, 'Components');
    if (project.settings.useItemModel && pack.custom_model_data === undefined && components.item_model === undefined) {
      resolved.Components = { item_model: `nexo:${item.itemId}`, ...components };
    }
  }
  if (context.itemModel) {
    resolved.Components = { ...section(resolved, 'Components'), item_model: context.itemModel };
  }
  for (const extra of context.extraConfig ?? []) {
    if (extra.ifMissing && getPath(resolved as ConfigObject, extra.path) !== undefined) continue;
    setPath(resolved as ConfigObject, extra.path, deepClone(extra.value) as ConfigValue);
  }
  const armor = context.armor;
  if (armor) {
    // The additional YAML is written over the result, so its material is the one Nexo gets
    const finalMaterial = effectiveMaterial(item).toUpperCase();
    const components = section(resolved, 'Components');
    const equippable = section(components, 'equippable');
    const slot = equippable.slot ?? slotForMaterial(finalMaterial) ?? armor.slot ?? 'HEAD';
    const entities = armor.entities;
    const withEntities =
      (slot === 'BODY' || slot === 'SADDLE') && entities.length > 0 && equippable.allowed_entity_types === undefined
        ? { allowed_entity_types: entities }
        : {};
    // Elytra wings without material ELYTRA need the glider component, otherwise you cannot fly
    const needsGlider = armor.glider && finalMaterial !== 'ELYTRA' && components.glider === undefined;
    resolved.Components = {
      ...components,
      equippable: {
        slot,
        asset_id: equippable.asset_id ?? armor.assetId,
        ...withEntities,
        ...equippable,
      },
      ...(needsGlider && { glider: true }),
    };
  }
  for (const key of TOP_LEVEL_ORDER) {
    if (resolved[key] !== undefined && result[key] === undefined) result[key] = resolved[key];
  }
  for (const [key, value] of Object.entries(resolved)) {
    if (result[key] === undefined) result[key] = value;
  }

  // 4. Overlay custom YAML
  const raw = parseRawYaml(item.rawYaml);
  return { config: raw.value ? deepMerge(result, raw.value) : result, rawYamlError: raw.error };
}

/** The object at `key` (a YAML section such as Pack or Components), or an empty one. */
function section(parent: Record<string, unknown>, key: string): Record<string, unknown> {
  const value = parent[key];
  return isPlainObject(value) ? value : {};
}

/** Replaces @model with the model's key (dropped if the item has no model). */
function resolveTokens(value: unknown, modelKey: string | null): unknown {
  return mapData(value, (leaf) => (leaf === MODEL_TOKEN ? (modelKey ?? undefined) : leaf));
}
