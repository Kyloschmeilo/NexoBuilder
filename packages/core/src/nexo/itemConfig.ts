/**
 * Builds the final Nexo YAML object from an item:
 *  1. clean up the structured config (remove empty fields, resolve placeholders)
 *  2. add automatic values (itemname, material, Pack.model, Components.item_model)
 *  3. overlay the user's additional YAML
 */
import { deepClone, deepMerge, isPlainObject } from '../object';
import type { ConfigObject, ConfigValue, Item, Project } from '../project/types';
import { slotForMaterial } from './armor';
import type { Field } from './fields';
import { getPath, setPath } from './configPath';
import { itemMaterial } from './material';
import { CONFIG_PROPERTIES } from './schema';
import { MODEL_TOKEN } from './tokens';
import { parseYaml } from './yaml';

/** Order of the keys in the YAML (as in the Nexo docs) */
const TOP_LEVEL_ORDER = [
  'itemname',
  'material',
  'template',
  'templates',
  'lore',
  'color',
  'unbreakable',
  'excludeFromInventory',
  'excludeFromCommands',
  'Pack',
  'Components',
  'AttributeModifiers',
  'Enchantments',
  'ItemFlags',
  'PersistentData',
  'CustomArmor',
  'Mechanics',
];

export interface BuildContext {
  project: Project;
  item: Item;
  /** "namespace:path" of the model, or null if the item has no model */
  modelKey: string | null;
  /** Equipment asset for armor (namespace:set) */
  armorAssetId?: string | null;
  /** From the set's layers (elytra → CHEST, animal armor → BODY, saddle → SADDLE) */
  armor?: { slot: string | null; entities: string[]; glider: boolean } | null;
  /** Model keys of the variants (e.g. pulling_models → [...]) */
  variantKeys?: Record<string, string | string[] | undefined>;
  /** ItemModel generated by ResourcepackBuilder (inventory icon, connectable furniture) */
  itemModel?: string | null;
  /** Values that additional models need in the config (e.g. placements.wall.item_model) */
  extraConfig?: Array<{ path: string[]; value: unknown; ifMissing?: boolean }>;
}

/**
 * Problem with the item's additional YAML (YAML tab):
 * - `syntax`: the YAML does not parse; `message` is the YAML library's error text (English, not translated)
 * - `notAMapping`: the YAML is valid but not a key-value mapping (e.g. "Mechanics: ...")
 */
export type RawYamlError = { kind: 'syntax'; message: string } | { kind: 'notAMapping' };

export interface BuildResult {
  config: Record<string, unknown>;
  rawYamlError: RawYamlError | null;
}

export function buildItemConfig(context: BuildContext): BuildResult {
  const { item, project, modelKey } = context;
  const source = deepClone(item.config);

  // 1. Clean up properties according to the schema
  const cleaned: Record<string, unknown> = {};
  const handled = new Set<string>();
  const handledParents = new Set<string>();
  for (const def of CONFIG_PROPERTIES) {
    const value = getPath(source, def.path);
    if (value === undefined) continue;
    handled.add(def.path.join('.'));
    for (let i = 1; i < def.path.length; i++) handledParents.add(def.path.slice(0, i).join('.'));
    let pruned = pruneByField(value, def.field);
    if (pruned === undefined && def.keepEmpty && isPlainObject(value)) pruned = {};
    if (pruned !== undefined) setPath(cleaned as ConfigObject, def.path, pruned as ConfigValue);
  }
  // Take over values that belong to no known property unchanged
  copyUnknown(source, cleaned, [], handled, handledParents);

  // 2. Resolve placeholders
  const resolved = resolveTokens(cleaned, modelKey) as Record<string, unknown>;

  // 3. Automatic values
  const result: Record<string, unknown> = {};
  const name = item.displayName.trim();
  if (name) result.itemname = name;
  const material = itemMaterial(item);
  result.material = material;
  delete resolved.material;
  delete resolved.itemname;

  if (modelKey) {
    const variants = Object.fromEntries(Object.entries(context.variantKeys ?? {}).filter(([, v]) => v !== undefined && v.length > 0));
    const pack: Record<string, unknown> = { model: modelKey, ...variants, ...section(resolved, 'Pack') };
    resolved.Pack = pack;
    const components = section(resolved, 'Components');
    if (project.settings.useItemModel && pack.custom_model_data === undefined && components.item_model === undefined) {
      resolved.Components = { item_model: `nexo:${item.nexoId}`, ...components };
    }
  }
  if (context.itemModel) {
    resolved.Components = { ...section(resolved, 'Components'), item_model: context.itemModel };
  }
  for (const extra of context.extraConfig ?? []) {
    if (extra.ifMissing && getPath(resolved as ConfigObject, extra.path) !== undefined) continue;
    setPath(resolved as ConfigObject, extra.path, deepClone(extra.value) as ConfigValue);
  }
  if (context.armorAssetId) {
    const components = section(resolved, 'Components');
    const equippable = section(components, 'equippable');
    const slot = equippable.slot ?? slotForMaterial(material) ?? context.armor?.slot ?? 'HEAD';
    const entities = context.armor?.entities ?? [];
    const withEntities =
      (slot === 'BODY' || slot === 'SADDLE') && entities.length > 0 && equippable.allowed_entity_types === undefined
        ? { allowed_entity_types: entities }
        : {};
    // Elytra wings without material ELYTRA need the glider component, otherwise you cannot fly
    const needsGlider = context.armor?.glider && material !== 'ELYTRA' && components.glider === undefined;
    resolved.Components = {
      ...components,
      equippable: {
        slot,
        asset_id: equippable.asset_id ?? context.armorAssetId,
        ...withEntities,
        ...equippable,
      },
      ...(needsGlider && { glider: true }),
    };
  }
  for (const key of TOP_LEVEL_ORDER) {
    if (resolved[key] !== undefined && result[key] === undefined) result[key] = resolved[key];
  }
  for (const [key, value] of Object.entries(resolved)) {
    if (result[key] === undefined) result[key] = value;
  }

  // 4. Overlay custom YAML
  let rawYamlError: RawYamlError | null = null;
  if (item.rawYaml.trim()) {
    const parsed = parseYaml(item.rawYaml);
    if (parsed.error) {
      rawYamlError = { kind: 'syntax', message: parsed.error };
    } else if (parsed.value !== null && !isPlainObject(parsed.value)) {
      rawYamlError = { kind: 'notAMapping' };
    } else if (isPlainObject(parsed.value)) {
      return { config: deepMerge(result, parsed.value), rawYamlError: null };
    }
  }
  return { config: result, rawYamlError };
}

/** The object at `key` (a YAML section such as Pack or Components), or an empty one. */
function section(parent: Record<string, unknown>, key: string): Record<string, unknown> {
  const value = parent[key];
  return isPlainObject(value) ? value : {};
}

function copyUnknown(
  source: Record<string, unknown>,
  target: Record<string, unknown>,
  path: string[],
  handled: Set<string>,
  handledParents: Set<string>,
) {
  for (const [key, value] of Object.entries(source)) {
    const full = [...path, key];
    const id = full.join('.');
    if (handled.has(id)) continue;
    if (handledParents.has(id) && isPlainObject(value)) {
      const nested = section(target, key);
      copyUnknown(value, nested, full, handled, handledParents);
      if (Object.keys(nested).length > 0) target[key] = nested;
      continue;
    }
    const pruned = pruneGeneric(value);
    if (pruned !== undefined) target[key] = pruned;
  }
}

function resolveTokens(value: unknown, modelKey: string | null): unknown {
  if (value === MODEL_TOKEN) return modelKey ?? undefined;
  if (Array.isArray(value)) return value.map((v) => resolveTokens(v, modelKey)).filter((v) => v !== undefined);
  if (isPlainObject(value)) {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value)) {
      const r = resolveTokens(v, modelKey);
      if (r !== undefined) out[k] = r;
    }
    return out;
  }
  return value;
}

/* ====================================================================== Pruning */

function isEmptyString(v: unknown): boolean {
  return typeof v === 'string' && v.trim() === '';
}

/** Removes empty values according to the field description. Returns undefined if nothing is left. */
function pruneByField(value: unknown, field: Field): unknown {
  if (value === undefined || value === null) return undefined;
  switch (field.type) {
    case 'text':
      if (typeof value === 'string') return isEmptyString(value) ? undefined : value;
      return pruneGeneric(value);
    case 'number':
      if (typeof value === 'number') return Number.isFinite(value) ? value : undefined;
      if (typeof value === 'string') return isEmptyString(value) ? undefined : value;
      return undefined;
    case 'boolean':
      return typeof value === 'boolean' ? value : undefined;
    case 'select':
      return typeof value === 'string' && isEmptyString(value) ? undefined : value;
    case 'stringList': {
      const list = Array.isArray(value) ? value : [value];
      const strings = list.filter((v) => v !== undefined && v !== null).map((v) => (typeof v === 'string' ? v : String(v)));
      if (strings.every((s) => isEmptyString(s))) return undefined;
      const keepBlankLines = field.format === 'minimessage';
      const cleaned = keepBlankLines ? trimTrailingEmpty(strings) : strings.filter((s) => !isEmptyString(s));
      if (field.singleAsString && cleaned.length === 1) return cleaned[0];
      return cleaned;
    }
    case 'multiSelect': {
      const list = Array.isArray(value) ? value.filter((v) => typeof v === 'string' && v) : [];
      return list.length > 0 ? list : undefined;
    }
    case 'presence':
      return isPlainObject(value) || value === true ? {} : undefined;
    case 'yaml':
      return value;
    case 'texture':
      return typeof value === 'string' && value ? value : undefined;
    case 'object': {
      if (!isPlainObject(value)) return undefined;
      const out: Record<string, unknown> = {};
      const known = new Set(field.fields.map((f) => f.key));
      for (const child of field.fields) {
        if (child.key === '*') {
          // "all remaining keys" (e.g. effects in armor_effects)
          const rest: Record<string, unknown> = {};
          for (const [k, v] of Object.entries(value)) if (!known.has(k)) rest[k] = v;
          const prunedRest = pruneByField(rest, child);
          if (isPlainObject(prunedRest)) Object.assign(out, prunedRest);
          continue;
        }
        const pruned = pruneByField(value[child.key], child);
        if (pruned !== undefined) out[child.key] = pruned;
      }
      for (const [k, v] of Object.entries(value)) {
        if (known.has(k) || known.has('*')) continue;
        const pruned = pruneGeneric(v);
        if (pruned !== undefined) out[k] = pruned;
      }
      if (Object.keys(out).length === 0) return field.emptyValue === true ? true : undefined;
      return out;
    }
    case 'objectList': {
      if (!Array.isArray(value)) return undefined;
      const objectField: Field = { type: 'object', key: '', label: '', fields: field.fields };
      const list = value.map((v) => pruneByField(v, objectField)).filter((v) => v !== undefined);
      return list.length > 0 ? list : undefined;
    }
    case 'map': {
      if (!isPlainObject(value)) return undefined;
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(value)) {
        if (!k.trim() || field.reservedKeys?.includes(k)) continue;
        let pruned = pruneByField(v, field.value);
        // An effect without further details is still intended → keep the empty object
        if (pruned === undefined && isPlainObject(v)) pruned = {};
        if (pruned !== undefined) out[k] = pruned;
      }
      return Object.keys(out).length > 0 ? out : undefined;
    }
  }
}

function trimTrailingEmpty(list: string[]): string[] {
  const out = [...list];
  while (out.length > 0 && isEmptyString(out[out.length - 1])) out.pop();
  return out;
}

/** Pruning for values without a schema: remove empty strings/lists/objects. */
function pruneGeneric(value: unknown): unknown {
  if (value === undefined || value === null) return undefined;
  if (typeof value === 'string') return isEmptyString(value) ? undefined : value;
  if (typeof value === 'number') return Number.isFinite(value) ? value : undefined;
  if (Array.isArray(value)) {
    const list = value.map(pruneGeneric).filter((v) => v !== undefined);
    return list.length > 0 ? list : undefined;
  }
  if (isPlainObject(value)) {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value)) {
      const pruned = pruneGeneric(v);
      if (pruned !== undefined) out[k] = pruned;
    }
    return Object.keys(out).length > 0 ? out : undefined;
  }
  return value;
}
