/** Placeholder for "the model of this item" (replaced by the model path on export). */
export const MODEL_TOKEN = '@model';
/** Prefix for uploaded extra textures. */
export const ASSET_TOKEN_PREFIX = '@asset:';

export type PropertyGroup = 'general' | 'appearance' | 'attributes' | 'components' | 'mechanics';

/** `label` and `description` are message keys in the `schema` namespace. */
export const PROPERTY_GROUPS: Array<{ id: PropertyGroup; label: string; description: string }> = [
  { id: 'general', label: 'groups.general.label', description: 'groups.general.description' },
  { id: 'appearance', label: 'groups.appearance.label', description: 'groups.appearance.description' },
  { id: 'attributes', label: 'groups.attributes.label', description: 'groups.attributes.description' },
  { id: 'components', label: 'groups.components.label', description: 'groups.components.description' },
  { id: 'mechanics', label: 'groups.mechanics.label', description: 'groups.mechanics.description' },
];

export interface PropertyDef {
  id: string;
  group: PropertyGroup;
  /** Path in the item YAML, e.g. ['Components', 'food'] */
  path: string[];
  /** Message key in the `schema` namespace (the English Nexo feature name in both languages) */
  label: string;
  /** Message key in the `schema` namespace */
  description: string;
  field: Field;
  defaultValue: () => ConfigValue;
  minVersion?: string;
  /** Last version in which the property exists */
  maxVersion?: string;
  /** These properties are mutually exclusive */
  conflicts?: string[];
  /** Hint shown above the form – message key in the `schema` namespace */
  hint?: string;
  docs?: string;
  /** Write an empty object anyway (mechanic active, even without options) */
  keepEmpty?: boolean;
}

