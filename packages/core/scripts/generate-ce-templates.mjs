// Lists the templates of CraftEngine's default templates pack (resources/default_templates in the plugin jar) with the
// arguments each uses, as packages/core/src/craftEngine/defaultTemplates.ts. Run once per CraftEngine update:
//   node packages/core/scripts/generate-ce-templates.mjs <extracted jar>/resources/default_templates
// then `npx prettier --write packages/core/src/craftEngine/defaultTemplates.ts`. The app never reads the jar.
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';
import { templateArgumentNames } from '../src/craftEngine/templateArgs.ts';

const root = process.argv[2];
if (!root) throw new Error('Usage: node generate-ce-templates.mjs <default_templates folder>');
const pack = parse(fs.readFileSync(path.join(root, 'pack.yml'), 'utf8'));
// The plugin's version, from paper-plugin.yml at the root of the extracted jar (<jar>/resources/default_templates)
const pluginFile = path.join(root, '..', '..', 'paper-plugin.yml');
const pluginVersion = fs.existsSync(pluginFile) ? parse(fs.readFileSync(pluginFile, 'utf8')).version : undefined;
const folder = path.join(root, 'configuration', 'templates');

/** The YAML as CraftEngine loads it: a key `a::b` is the key `b` in the map `a` (StringKeyConstructor). */
function expandDeepKeys(value) {
  if (Array.isArray(value)) return value.map(expandDeepKeys);
  if (typeof value !== 'object' || value === null) return value;
  const result = {};
  for (const [key, entry] of Object.entries(value)) {
    const parts = key.split('::');
    let target = result;
    for (const part of parts.slice(0, -1)) {
      if (typeof target[part] !== 'object' || target[part] === null) target[part] = {};
      target = target[part];
    }
    target[parts.at(-1)] = expandDeepKeys(entry);
  }
  return result;
}

/** id → { file, body }, in file order (section keys `template(s)` with an optional `#suffix`) */
const bodies = new Map();
for (const file of fs
  .readdirSync(folder)
  .filter((name) => name.endsWith('.yml'))
  .sort()) {
  const config = expandDeepKeys(parse(fs.readFileSync(path.join(folder, file), 'utf8')));
  for (const [section, entries] of Object.entries(config)) {
    if (!/^templates?(#.*)?$/.test(section)) continue;
    for (const [key, body] of Object.entries(entries)) {
      const id = key.includes(':') ? key : `${pack.namespace}:${key}`;
      bodies.set(id, { file: file.replace(/\.yml$/, ''), body });
    }
  }
}

const names = new Map();
const visiting = new Set();
function lookup(id) {
  if (names.has(id)) return names.get(id);
  const entry = bodies.get(id);
  if (!entry || visiting.has(id)) return undefined;
  visiting.add(id);
  const result = templateArgumentNames(entry.body, lookup);
  visiting.delete(id);
  names.set(id, result);
  return result;
}

const lines = [...bodies].map(([id, { file }]) => {
  const { required, optional } = lookup(id);
  const parts = [`id: ${JSON.stringify(id)}`, `file: ${JSON.stringify(file)}`];
  if (required.length > 0) parts.push(`required: ${JSON.stringify(required)}`);
  if (optional.length > 0) parts.push(`optional: ${JSON.stringify(optional)}`);
  return `  { ${parts.join(', ')} },`;
});

const out = `// Generated by packages/core/scripts/generate-ce-templates.mjs from the default_templates pack (version ${pack.version ?? '?'})
// of CraftEngine ${pluginVersion ?? '?'}. Do not edit by hand.

/** A template of CraftEngine's default templates pack: its id, the file it is in, and the arguments it uses. */
export interface DefaultTemplate {
  id: string;
  /** The file in default_templates/configuration/templates (block_settings, block_states, events, loot_tables) */
  file: string;
  /** Arguments it needs (CraftEngine rejects the config without them) */
  required?: readonly string[];
  /** Arguments with a default */
  optional?: readonly string[];
}

/** Every template of the default templates pack, in file order. */
export const CE_DEFAULT_TEMPLATES: readonly DefaultTemplate[] = [
${lines.join('\n')}
];
`;
const target = path.join(import.meta.dirname, '..', 'src', 'craftEngine', 'defaultTemplates.ts');
fs.writeFileSync(target, out);
console.log(`${bodies.size} templates written to ${target}`);
